#!/usr/bin/env python3
"""Key-3 "Road Central Line" layer data from the user's own GIS drawing (docs/road_centre_view/road_centre_view.shp, CLASS = 6 / 4 / 2 / C / L).
Writes src/roads/debug/RoadCentreData.ts (classes 6 / 4 / 2) and src/roads/debug/HousingStreetData.ts (classes C / L). No pip packages needed.
Run from the project root:  python3 tools/centre-view-import.py [path/to/road_centre_view]      (default docs/road_centre_view/road_centre_view)
Grid -> game world (inverse of src/export/GisWriter.ts toGrid):  x = easting - 5000,  z = 5000 - northing.
Road numbers (file order, fid = 0-based row of the shapefile):  R6-9, R6-10 ... (R6-1..R6-8 are the roads already built),  R4-1 ...,  R2-1 ...,  C-1 ...,  L-1 ...
Do NOT rerun tools/map2-export-ts.py or tools/housing-export-ts.py any more: they would bring the old planned / housing lines back."""
import math, os, struct, sys

H = 5000.0           # Config.world.size / 2
R6_FIRST = 9         # built 6-lane roads are M6-1, R6-2 ... R6-8
base = sys.argv[1] if len(sys.argv) > 1 else 'docs/road_centre_view/road_centre_view'


def read_shp(path):
    d = open(path + '.shp', 'rb').read()
    pos = 100
    out = []
    while pos < len(d):
        _, clen = struct.unpack('>ii', d[pos:pos + 8])
        pos += 8
        rec = d[pos:pos + clen * 2]
        pos += clen * 2
        t = struct.unpack('<i', rec[:4])[0]
        if t not in (3, 13, 23):
            out.append(None)
            continue
        nparts, npts = struct.unpack('<ii', rec[36:44])
        parts = list(struct.unpack('<%di' % nparts, rec[44:44 + 4 * nparts])) + [npts]
        o = 44 + 4 * nparts
        pts = [struct.unpack('<2d', rec[o + 16 * i:o + 16 * i + 16]) for i in range(npts)]
        out.append([pts[parts[i]:parts[i + 1]] for i in range(nparts)])
    return out


def read_dbf(path):
    d = open(path + '.dbf', 'rb').read()
    n = struct.unpack('<i', d[4:8])[0]
    hl, rl = struct.unpack('<hh', d[8:12])
    fields = []
    o = 32
    while d[o] != 0x0D:
        fields.append((d[o:o + 11].split(b'\0')[0].decode(), d[o + 16]))
        o += 32
    rows = []
    for i in range(n):
        r = d[hl + i * rl:hl + (i + 1) * rl]
        p = 1
        row = {}
        for name, ln in fields:
            row[name] = r[p:p + ln].decode('cp437', errors='replace').strip()
            p += ln
        rows.append(row)
    return rows


geoms = read_shp(base)
rows = read_dbf(base)
assert len(geoms) == len(rows), 'shp / dbf row count differs'

lines = {'6': [], '4': [], '2': [], 'C': [], 'L': []}
skipped = []
for fid, (g, r) in enumerate(zip(geoms, rows)):
    cls = r['CLASS'].upper()
    if g is None or cls not in lines:
        skipped.append((fid, 'no geometry or unknown CLASS %r' % r['CLASS']))
        continue
    for part in g:                       # a multi-part feature becomes one line per part
        pts = []
        for e, n in part:
            q = [round(e - H), round(H - n)]
            if not pts or pts[-1] != q:
                pts.append(q)
        if len(pts) < 2:
            skipped.append((fid, 'shorter than 1 m'))
            continue
        lines[cls].append((fid, pts))


def length(p):
    return sum(math.dist(p[i], p[i + 1]) for i in range(len(p) - 1))


def js(p):
    return '[' + ','.join('[%d,%d]' % (x, z) for x, z in p) + ']'


A = ["// GENERATED by tools/centre-view-import.py from docs/road_centre_view/road_centre_view.shp (the user's own centreline drawing). Do not edit: rerun the script.",
     '// Centrelines of the new 6 / 4 / 2 lane roads for the Road Central Line debug layer, key 3 (NOT real roads: no profile, no physics, no AI). x east, z south, whole metres. fid = row of the shapefile.',
     'export interface CentreRoad { id: string; cls: 6 | 4 | 2; pts: number[][]; flag?: string; }',
     'export interface CentreJunction { id: string; x: number; z: number; }',
     'export const CENTRE_CLASSES = [6, 4, 2];',
     'export const CENTRE_ROADS: CentreRoad[] = [']
for cls, first in (('6', R6_FIRST), ('4', 1), ('2', 1)):
    for k, (fid, pts) in enumerate(lines[cls]):
        A.append("  { id: 'R%s-%d', cls: %s, pts: %s }, // fid %d" % (cls, first + k, cls, js(pts), fid))
A += ['];', 'export const CENTRE_JUNCTIONS: CentreJunction[] = [];']

B = ["// GENERATED by tools/centre-view-import.py from docs/road_centre_view/road_centre_view.shp (the user's own centreline drawing). Do not edit: rerun the script.",
     '// Centrelines of the C (collector) and L (local) streets for the Road Central Line debug layer, key 3 (NOT real roads: no profile, no physics, no AI). x east, z south, whole metres. fid = row of the shapefile.',
     "export interface HousingStreet { id: string; cls: 'A' | 'C' | 'L'; pts: number[][]; }",
     'export interface HousingJunction { id: string; x: number; z: number; c: string; }',
     'export const HOUSING_STREETS: HousingStreet[] = [']
for cls in ('C', 'L'):
    for k, (fid, pts) in enumerate(lines[cls]):
        B.append("  { id: '%s-%d', cls: '%s', pts: %s }, // fid %d" % (cls, k + 1, cls, js(pts), fid))
B += ['];', 'export const HOUSING_JUNCTIONS: HousingJunction[] = [];']

for path, L in (('src/roads/debug/RoadCentreData.ts', A), ('src/roads/debug/HousingStreetData.ts', B)):
    open(path, 'w', newline='').write('\r\n'.join(L) + '\r\n')
    print(path, os.path.getsize(path), 'bytes')
for c in lines:
    print('class', c, ':', len(lines[c]), 'lines,', round(sum(length(p) for _, p in lines[c])), 'm')
for s in skipped:
    print('skipped fid', s)
