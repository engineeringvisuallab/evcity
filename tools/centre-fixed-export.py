# STEP 21.3: copy the FIXED centrelines (docs/centre_fixed.json) into src/roads/debug/RoadCentreData.ts and HousingStreetData.ts.
# Run scripts/centre-fix.ts BEFORE this script. Keeps ids, classes, order and fid comments; only the points change (whole metres, Douglas-Peucker 1 m).
# Old files are copied to docs/centre_before_21_3/ first (once). Do NOT run tools/centre-view-import.py afterwards.
import json, math, os, re, shutil
J = json.load(open('docs/centre_fixed.json'))
FIX = {l['id']: l['pts'] for l in J['lines'] if not l['built'] and not l.get('dropped')}
DROP = {l['id'] for l in J['lines'] if l.get('dropped')}   # STEP 21.4b: rim lines with no good 100 m piece, their rows are removed
def dp(p, tol):
    if len(p) < 3: return p
    ax, az = p[0]; bx, bz = p[-1]; L = math.hypot(bx - ax, bz - az) or 1e-9
    dmax, k = -1, 0
    for i in range(1, len(p) - 1):
        d = abs((bx - ax) * (az - p[i][1]) - (ax - p[i][0]) * (bz - az)) / L
        if d > dmax: dmax, k = d, i
    if dmax <= tol: return [p[0], p[-1]]
    return dp(p[:k + 1], tol)[:-1] + dp(p[k:], tol)
os.makedirs('docs/centre_before_21_3', exist_ok=True)
n = 0; nDrop = 0
for path in ('src/roads/debug/RoadCentreData.ts', 'src/roads/debug/HousingStreetData.ts'):
    bak = 'docs/centre_before_21_3/' + os.path.basename(path)
    if not os.path.exists(bak): shutil.copy(path, bak)
    txt = open(bak, newline='').read()
    out = []
    for line in txt.split('\r\n'):
        m = re.match(r"^  \{ id: '([^']+)'", line)
        if m and m.group(1) in DROP: nDrop += 1; continue
        if m and m.group(1) in FIX:
            pts = [[int(round(x)), int(round(z))] for x, z in FIX[m.group(1)]]
            pts = dp(pts, 1.0)
            arr = '[' + ','.join('[%d,%d]' % (x, z) for x, z in pts) + ']'
            line = re.sub(r'pts: \[\[.*?\]\] \}', 'pts: ' + arr + ' }', line, count=1); n += 1
        if line.startswith('// GENERATED by tools/centre-view-import.py'):
            line = "// GENERATED by tools/centre-view-import.py from docs/road_centre_view/road_centre_view.shp, then FIXED by step 21.3 (tools/centre-fixed-export.py from docs/centre_fixed.json). The drawn version is in docs/centre_before_21_3/. Do not edit; do not rerun centre-view-import.py."
        out.append(line)
    open(path, 'w', newline='').write('\r\n'.join(out))
    print(path, os.path.getsize(path), 'bytes')
print(n, 'lines written of', len(FIX), '; rows removed', nDrop, 'of', len(DROP), 'dropped lines')
