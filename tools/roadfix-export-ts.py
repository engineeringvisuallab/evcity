#!/usr/bin/env python3
"""MAP-2 viewer data: docs/map_all_roads_v3.json -> src/roads/debug/RoadCentreData.ts (lean: points every ~20 m, whole metres).
Run: python3 tools/map2-export-ts.py 6        (classes to include: 6, then 6 4, then 6 4 2)"""
import json, sys, math
sys.path.insert(0,'tools')
import roadfix_hier as map2_hier
cls=[int(a) for a in sys.argv[1:]] or [6]
J=json.load(open('docs/map_all_roads_v3.json'))
def thin(P,step=20.0):
    out=[P[0]]; acc=0.0
    for a,b in zip(P[:-1],P[1:]):
        acc+=math.hypot(b[0]-a[0],b[1]-a[1])
        if acc>=step: out.append(b); acc=0.0
    if out[-1]!=P[-1]: out.append(P[-1])
    return [[round(x),round(z)] for x,z in out]
_J,_poly,_cl,_ids,_ok,_joined=map2_hier.analyse()  # class-sequence rule (V3): flag '!' = nothing bigger within 100 m, '~' = stops short of it
flag={i:('!' if i not in _ok else '~') for i in _ids if i not in _joined}
for _r in J['roads']:
    _t=_r.get('roadfix',{}).get('tunnel')
    if _t: flag[_r['id']]=flag.get(_r['id'],'')+' T%dm'%_t['len_m']
    _x=_r.get('roadfix',{}).get('railx')
    if _x:
        _o=sum(1 for q in _x if q['type']=='overpass'); _u=sum(1 for q in _x if q['type']=='underpass')
        if _o or _u: flag[_r['id']]=flag.get(_r['id'],'')+(' RO%d'%_o if _o else '')+(' RU%d'%_u if _u else '')
    _b=_r.get('roadfix',{}).get('bridges')
    if _b: flag[_r['id']]=flag.get(_r['id'],'')+' B%dm'%sum(q['len'] for q in _b)
    _s=_r.get('roadfix',{}).get('struct')
    if _s: flag[_r['id']]=flag.get(_r['id'],'')+((' T%dm'%_s['tunnel_m']) if _s['tunnel_m'] else '')+((' V%dm'%_s['viaduct_m']) if _s['viaduct_m'] else '')
roads=[r for r in J['roads'] if r['cls'] in cls]
ids={r['id'] for r in roads}
js=[j for j in J['junctions'] if any(m in ids for m in j['roads'])]
L=['// GENERATED by tools/map2-export-ts.py from docs/map_all_roads_v3.json (STEP MAP-2 viewer). Do not edit: rerun the script.',
   '// Desire-line centrelines for the Road Central Line debug layer (NOT real roads). x east, z south, whole metres.',
   'export interface CentreRoad { id: string; cls: 6 | 4 | 2; pts: number[][]; flag?: string; }','export interface CentreJunction { id: string; x: number; z: number; }',
   'export const CENTRE_CLASSES = %s;'%json.dumps(cls),
   'export const CENTRE_ROADS: CentreRoad[] = [']
for r in roads: L.append("  { id: '%s', cls: %d, pts: %s%s },"%(r['id'],r['cls'],json.dumps(thin(r['pts']),separators=(',',':')),(", flag: '%s'"%flag[r['id']]) if r['id'] in flag else ''))
L.append('];'); L.append('export const CENTRE_JUNCTIONS: CentreJunction[] = [')
for j in js: L.append("  { id: '%s', x: %d, z: %d },"%(j['id'],round(j['x']),round(j['z'])))
L.append('];')
open('src/roads/debug/RoadCentreData.ts','w').write('\r\n'.join(L)+'\r\n'); print(len(roads),'roads',len(js),'junctions')
