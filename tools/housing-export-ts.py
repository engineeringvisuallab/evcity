#!/usr/bin/env python3
"""STEP C viewer data: docs/housing_streets.json -> src/roads/debug/HousingStreetData.ts (lean: ~20 m points, more on curves, whole metres).
Run: python3 tools/housing-export-ts.py        (after: npx tsx scripts/housing-streets.ts docs)"""
import json, math
J = json.load(open('docs/housing_streets.json'))
def thin(P, step=20.0, ang=3.5):
    out = [P[0]]; acc = 0.0; last_h = None
    for a, b in zip(P[:-1], P[1:]):
        acc += math.hypot(b[0]-a[0], b[1]-a[1])
        h = math.atan2(b[1]-a[1], b[0]-a[0])
        if last_h is None: last_h = h
        turn = abs((h - last_h + math.pi) % (2*math.pi) - math.pi)
        if acc >= step or (acc >= 6 and turn > math.radians(ang)):
            out.append(b); acc = 0.0; last_h = h
    if out[-1] != P[-1]: out.append(P[-1])
    # whole metres, drop repeated points
    res = []
    for x, z in out:
        q = [round(x), round(z)]
        if not res or res[-1] != q: res.append(q)
    return res
L = ['// GENERATED by tools/housing-export-ts.py from docs/housing_streets.json (STEP C housing street centrelines). Do not edit: rerun the script.',
     '// Plan-view centrelines of the housing streets for the Road Central Line debug layer (NOT real roads: no profile, no physics, no AI). x east, z south, whole metres.',
     "export interface HousingStreet { id: string; cls: 'A' | 'C' | 'L'; pts: number[][]; }",
     'export interface HousingJunction { id: string; x: number; z: number; c: string; }',
     'export const HOUSING_STREETS: HousingStreet[] = [']
nj = 0; ns = 0
for s in J['sites']:
    for st in s['streets']:
        L.append("  { id: '%s', cls: '%s', pts: %s }," % (st['id'], st['cls'], json.dumps(thin(st['pts']), separators=(',', ':')))); ns += 1
L.append('];'); L.append('export const HOUSING_JUNCTIONS: HousingJunction[] = [')
for s in J['sites']:
    for j in s['junctions']:
        L.append("  { id: '%s', x: %d, z: %d, c: '%s' }," % (j['id'], round(j['x']), round(j['z']), j['cls'])); nj += 1
L.append('];')
open('src/roads/debug/HousingStreetData.ts', 'w', newline='').write('\r\n'.join(L) + '\r\n')
import os
print(ns, 'streets', nj, 'junctions', os.path.getsize('src/roads/debug/HousingStreetData.ts'), 'bytes')
