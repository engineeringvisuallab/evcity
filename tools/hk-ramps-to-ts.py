#!/usr/bin/env python3
# STEP HK-9a: docs/hk_loops_a.json + docs/hk_loops_b.json -> src/roads/ring/HkRampData.ts (CRLF, like the other files of src/roads/ring). Run: python3 tools/hk-ramps-to-ts.py [docs dir] [out file]
import json, sys
d = sys.argv[1] if len(sys.argv) > 1 else 'docs'
out = sys.argv[2] if len(sys.argv) > 2 else 'src/roads/ring/HkRampData.ts'
A = json.load(open(f'{d}/hk_loops_a.json')); B = json.load(open(f'{d}/hk_loops_b.json'))
loops = [('SE', A['se'], A['rows']['SE']), ('NE', A['ne'], A['rows']['NE']), ('NW', B['nw'], B['rows']['NW']), ('SW', B['sw'], B['rows']['SW'])]
L = []
L.append("// STEP HK-9a: centrelines of the four EQUAL loop ramps (R 80 m, V45) of the Hatikamrul-type interchange. Generated by tools/hk-ramps-to-ts.py from docs/hk_loops_a.json (SE, NE) and docs/hk_loops_b.json (NW, SW); do not edit by hand.")
L.append("// LOCAL frame: origin = the ring S node, x EAST (along the ring), y NORTH (toward the J1-S arm), metres, left-hand traffic. yA = level at the C-D road end, yB = level where the loop joins the ring lane (HK-4 / HK-5 numbers); peak = peak grade of the smoothstep profile (HK numbers, cross-checked in scripts/hk-ramps-check.ts).")
L.append("export interface HkLoopData { readonly id: string; readonly yA: number; readonly yB: number; readonly peak: number; readonly viaductM: number; readonly pts: readonly (readonly [number, number])[] }")
L.append("/** Half width of a single-lane ramp (m), HK-5. */")
L.append("export const HK_RAMP_HALF = 4.2;")
L.append("export const HK_LOOPS: readonly HkLoopData[] = [")
for q, pts, r in loops:
    P = ','.join(f"[{p['x']:.2f},{p['y']:.2f}]" for p in pts)
    L.append(f"  {{ id: 'HK-{q}', yA: {r['yA']:.3f}, yB: {r['yB']:.3f}, peak: {r['peak']:.5f}, viaductM: {r['viaductM']}, pts: [{P}] }},")
L.append("];")
open(out, 'w', newline='').write('\r\n'.join(L) + '\r\n')
print(out, sum(len(x[1]) for x in loops), 'points')
