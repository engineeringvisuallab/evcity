// RELOCATE BUILDINGS OFF ROADS AND RAILWAY (user 2026-11-20: "road er upore and rail er upore kono building thakbe na. thik jaigai place koro").
// Every placed building (hand placed, city fill, residential) whose footprint is on a road (ribbon + footpath, gap < 1 m) or in / touching the rail corridor
// is MOVED to the nearest free spot of the same world zone: >= 3 m from every road edge, >= 6 m from the rail corridor, no water, no keep-out site,
// no engineering area, outside every city plot, (houses may leave their old zone strip, landmarks keep their zone), >= 3 m from every other building, same ground-range rule as scripts/building-clear-roads.ts.
// Buildings inside the city plots (generated by tools/city-plots-plan.py) are never touched. Nothing is deleted: a building with no spot stays and is listed.
// Run: node --experimental-transform-types --import ./scripts/reg.mjs scripts/building-relocate.ts          (dry run)
//      node --experimental-transform-types --import ./scripts/reg.mjs scripts/building-relocate.ts --apply  (edits Placements.ts, PlacementsFill.ts, PlacementsResidential.ts + docs/building_relocation.json)
