const CELL = 100;
interface P { x: number; z: number; w: number }
const grid = new Map<string, P[]>();
for (const r of R.roads) {
  if (r.earth) continue;
  for (let i = 1; i < r.xs.length; i++) {
    const L = Math.hypot(r.xs[i] - r.xs[i - 1], r.zs[i] - r.zs[i - 1]), n = Math.max(1, Math.ceil(L / 2));
    for (let k = 0; k < n; k++) {
      const t = k / n, x = r.xs[i - 1] + (r.xs[i] - r.xs[i - 1]) * t, z = r.zs[i - 1] + (r.zs[i] - r.zs[i - 1]) * t;
      const city = R.isCityPoint(x, z) || r.tier === 4;
      const key = `${Math.floor(x / CELL)},${Math.floor(z / CELL)}`;
      const p = { x, z, w: r.halfWidth + (city ? Math.max(FOOT, r.shoulder, WALK) : r.shoulder) };
      const a = grid.get(key); if (a) a.push(p); else grid.set(key, [p]);
    }
  }
}
const near = (x: number, z: number, rad: number): P[] => { const out: P[] = []; for (let a = Math.floor((x - rad) / CELL); a <= Math.floor((x + rad) / CELL); a++) for (let b = Math.floor((z - rad) / CELL); b <= Math.floor((z + rad) / CELL); b++) { const g = grid.get(`${a},${b}`); if (g) for (const p of g) out.push(p); } return out; };
type B = { x: number; z: number; yaw: number; W: number; D: number };
const roadGap = (b: B): number => {
  const c = Math.cos(b.yaw), s = Math.sin(b.yaw), hx = b.W / 2, hz = b.D / 2; let gap = 1e9;
  for (const p of near(b.x, b.z, Math.hypot(hx, hz) + 40)) { const dx = p.x - b.x, dz = p.z - b.z, lx = dx * c - dz * s, lz = dx * s + dz * c; gap = Math.min(gap, Math.hypot(Math.max(Math.abs(lx) - hx, 0), Math.max(Math.abs(lz) - hz, 0)) - p.w); }
  return gap;
};
const railShare = (b: B, margin: number): number => {
  const c = Math.cos(b.yaw), s = Math.sin(b.yaw); let n = 0, hit = 0;
  for (let lx = -b.W / 2; lx <= b.W / 2 + 1e-6; lx += Math.max(1, b.W / Math.ceil(b.W / 3))) for (let lz = -b.D / 2; lz <= b.D / 2 + 1e-6; lz += Math.max(1, b.D / Math.ceil(b.D / 3))) { n++; if (rail.inCorridor(b.x + lx * c + lz * s, b.z - lx * s + lz * c, margin)) hit++; }
  return hit / Math.max(1, n);
};
const flagged = (b: B): boolean => roadGap(b) < FLAG_GAP || railShare(b, RAIL_FLAG) > 0;
const corners = (q: B): [number, number][] => { const c = Math.cos(q.yaw), s = Math.sin(q.yaw); return ([[-1, -1], [1, -1], [1, 1], [-1, 1]] as const).map(([fx, fz]) => [q.x + (fx * q.W) / 2 * c + (fz * q.D) / 2 * s, q.z - (fx * q.W) / 2 * s + (fz * q.D) / 2 * c] as [number, number]); };
const rectsOverlap = (a: B, b: B, m: number): boolean => {
  if (Math.hypot(a.x - b.x, a.z - b.z) > Math.hypot(a.W, a.D) / 2 + Math.hypot(b.W, b.D) / 2 + m) return false;
  const ca = corners(a), cb = corners(b);
  for (const q of [a, b]) { const c = Math.cos(q.yaw), s = Math.sin(q.yaw); for (const [ax, az] of [[c, -s], [s, c]] as const) { const pa = ca.map(([x, z]) => x * ax + z * az), pb = cb.map(([x, z]) => x * ax + z * az); if (Math.max(...pa) + m < Math.min(...pb) || Math.max(...pb) + m < Math.min(...pa)) return false; } }
  return true;
};
// ---- plots (never build inside one: the houses inside a plot are dropped by the game) ----
const inPlot = (x: number, z: number, m: number): boolean => { for (const p of CITY_PLOTS) { if (Math.abs(x - p.c[0]) > 300 || Math.abs(z - p.c[1]) > 300) continue; let neg = false, pos = false; for (let i = 0; i < 4; i++) { const a = p.poly[i]!, b = p.poly[(i + 1) % 4]!; const ex = b[0] - a[0], ez = b[1] - a[1], cr = (ex * (z - a[1]) - ez * (x - a[0])) / Math.hypot(ex, ez); if (cr < -m) neg = true; else if (cr > m) pos = true; } if (!(neg && pos)) return true; } return false; };
// ---- all buildings the game draws ----
type Src = 'hand' | 'fill' | 'res';
interface It { p: BuildingPlacement; src: Src; x: number; z: number; plot: boolean }
const plotSet = new Set<BuildingPlacement>(CITY_PLOT_BUILDINGS);
const items: It[] = [];
for (const p of BUILDING_PLACEMENTS) items.push({ p, src: 'hand', x: p.x, z: p.z, plot: plotSet.has(p) });
for (const p of FILL_PLACEMENTS) if (!inPlot(p.x, p.z, 0)) items.push({ p, src: 'fill', x: p.x, z: p.z, plot: false });
for (const p of RESIDENTIAL_PLACEMENTS) if (!inPlot(p.x, p.z, 0)) items.push({ p, src: 'res', x: p.x, z: p.z, plot: false });
const bOf = (it: It): B => ({ x: it.x, z: it.z, yaw: it.p.yaw, W: it.p.W, D: it.p.D });
const OC = 40; const oh = new Map<string, It[]>();
const okey = (x: number, z: number): string => `${Math.floor(x / OC)},${Math.floor(z / OC)}`;
const ohAdd = (it: It): void => { const k = okey(it.x, it.z); const a = oh.get(k); if (a) a.push(it); else oh.set(k, [it]); };
const ohDel = (it: It): void => { const a = oh.get(okey(it.x, it.z)); if (a) a.splice(a.indexOf(it), 1); };
for (const it of items) ohAdd(it);
const overlapsAny = (self: It, b: B): boolean => { const rad = Math.hypot(b.W, b.D) / 2 + 60; for (let a = Math.floor((b.x - rad) / OC); a <= Math.floor((b.x + rad) / OC); a++) for (let c = Math.floor((b.z - rad) / OC); c <= Math.floor((b.z + rad) / OC); c++) { const l = oh.get(`${a},${c}`); if (l) for (const o of l) if (o !== self && rectsOverlap(b, bOf(o), 3)) return true; } return false; };
function okSpot(it: It, x: number, z: number): boolean {
  const p = it.p, b: B = { x, z, yaw: p.yaw, W: p.W, D: p.D };
  if (roadGap(b) < NEED_GAP) return false;
  if (it.src === 'hand' && getWorldZoneAt(x, z).id !== p.zone) return false; // landmarks stay in their zone; houses only need free land near where they were (the s0-* zones are thin strips along the old roads)
  for (const [cx, cz] of corners(b)) if (inPlot(cx, cz, 3)) return false;
  if (inPlot(x, z, 3)) return false;
  const c = Math.cos(p.yaw), sn = Math.sin(p.yaw), nx = Math.ceil(p.W / 3), nz = Math.ceil(p.D / 3);
  let mn = 1e9, mx = -1e9;
  for (let i = 0; i <= nx; i++) for (let j = 0; j <= nz; j++) {
    const lx = -p.W / 2 + (i / nx) * p.W, lz = -p.D / 2 + (j / nz) * p.D, X = x + lx * c + lz * sn, Z = z - lx * sn + lz * c;
    if (R.surfaceAt(X, Z) !== 0 || rail.inCorridor(X, Z, NEED_RAIL)) return false;
    if (libraryKeepout(X, Z) || mallKeepout(X, Z) || evlabKeepout(X, Z) || protoKeepout(X, Z) || infraKeepout(X, Z) || airportKeepout(X, Z) || agroKeepout(X, Z) || getEngineeringAreaAt(X, Z)) return false;
    gen.sample(X, Z, sc); if (sc.water === sc.water && sc.h < sc.water + 0.3) return false;
    mn = Math.min(mn, sc.h); mx = Math.max(mx, sc.h);
  }
  if (mx - mn > 14.5) return false;
  return !overlapsAny(it, b);
}
