// STEP G7g (headless): export the two slip roads of the JX-2 north half interchange as game data. Only READS docs/r6_g7g_north.json (made by scripts/r6-g7g-north.ts), writes src/roads/r6/R6SlipData.ts.
// Run: npx tsx scripts/r6-export-slips.ts docs
import { readFileSync, writeFileSync } from 'node:fs';
const dir = process.argv[2] ?? 'docs';
const N = JSON.parse(readFileSync(dir + '/r6_g7g_north.json', 'utf8')) as { es: { pts: number[][]; ys: number[]; len: number }; en: { pts: number[][]; ys: number[]; len: number } };
const one = (name: string, from: string, to: string, q: { pts: number[][]; ys: number[]; len: number }) => {
  if (q.pts.length !== q.ys.length) throw new Error(`${name}: points and heights differ`);
  console.log(`${name}: ${q.pts.length} points, ${q.len.toFixed(1)} m, level ${q.ys[0]} -> ${q.ys[q.ys.length - 1]} m, ${from} -> ${to}`);
  return `  { name: '${name}', from: '${from}', to: '${to}', pts: ${JSON.stringify(q.pts.map((p) => [+p[0].toFixed(1), +p[1].toFixed(1)]))}, ys: ${JSON.stringify(q.ys.map((v) => +v.toFixed(2)))} },`;
};
writeFileSync('src/roads/r6/R6SlipData.ts', `// GENERATED by scripts/r6-export-slips.ts (STEP G7g). Do not edit: rerun the script (source docs/r6_g7g_north.json, scripts/r6-g7g-north.ts).
// The two slip roads (V50: R 75 m, Ls 35 m, Ts 93 m) of the JX-2 HALF interchange on the NORTH side of the J1-E arm, tap at arm s 1808 (arm level 36.05 m = ground).
// Points run in the direction of travel (one-way, 1 lane). Heights are finished surface levels (used exactly, fixedY).
//   R6-8:m1 exit slip : leaves the ring-bound carriageway of J1-E at the nose (arm s 1705, level 38.78 m) and ends on the lane line of the stem R6-8 start.
//   R6-8:m2 entry slip: starts on the other lane line of the stem R6-8 start and merges into the ring-bound carriageway at arm s 1913 (slip end 33.01 m, arm 32.97 m).
export interface R6SlipData { name: string; from: string; to: string; pts: number[][]; ys: number[] }
export const R6_SLIP_DATA: R6SlipData[] = [
${one('R6-8:m1', 'J1-E arm s 1705', 'R6-8 start', N.es)}
${one('R6-8:m2', 'R6-8 start', 'J1-E arm s 1913', N.en)}
];
`);
